# Обратный маппинг: форма слова -> базовая форма и приоритет
_reverse_mapping: Dict[str, Tuple[str, int]] = None
_stop_words_lower: Set[str] = None


def _build_reverse_mapping():
    """Строит обратный маппинг форм слов на базовые формы и приоритеты"""
    global _reverse_mapping
    if _reverse_mapping is not None:
        return _reverse_mapping
    
    _reverse_mapping = {}
    for base_form, term_data in LEGAL_TERMS.items():
        priority = term_data['priority']
        # Добавляем базовую форму
        _reverse_mapping[base_form] = (base_form, priority)
        # Добавляем все формы
        for form in term_data['forms']:
            _reverse_mapping[form.lower()] = (base_form, priority)
    
    return _reverse_mapping


def _get_stop_words_lower():
    """Возвращает стоп-слова в нижнем регистре"""
    global _stop_words_lower
    if _stop_words_lower is not None:
        return _stop_words_lower
    
    _stop_words_lower = {word.lower() for word in STOP_WORDS}
    return _stop_words_lower


def get_word_info(word: str) -> Tuple[Optional[str], int]:
    """
    Получает информацию о слове: базовую форму и приоритет
    
    Args:
        word: Слово для анализа
        
    Returns:
        Tuple: (базовая_форма, приоритет) или (None, PRIORITY_NONE) если слово незначимое
    """
    word_lower = word.lower().strip()
    
    # Проверяем стоп-слова
    if word_lower in _get_stop_words_lower():
        return None, PRIORITY_NONE
    
    # Проверяем юридические термины
    mapping = _build_reverse_mapping()
    if word_lower in mapping:
        base_form, priority = mapping[word_lower]
        return base_form, priority
    
    # Если слово не найдено в словаре, но длиннее 3 символов - возвращаем как есть с низким приоритетом
    if len(word_lower) > 3:
        return word_lower, PRIORITY_LOW
    
    return None, PRIORITY_NONE


def rank_and_filter_query(query: str) -> List[Tuple[str, int]]:
    """
    Ранжирует и фильтрует слова из запроса по значимости
    
    Args:
        query: Исходный запрос
        
    Returns:
        Список кортежей (базовая_форма, приоритет), отсортированный по приоритету (от высокого к низкому)
    """
    if not query:
        return []
    
    # Извлекаем слова из запроса
    words = re.findall(r'\b\w+\b', query.lower())
    
    # Получаем информацию о каждом слове
    ranked_words = []
    seen_base_forms = set()  # Чтобы не дублировать базовые формы
    
    for word in words:
        base_form, priority = get_word_info(word)
        
        # Пропускаем незначащие слова
        if base_form is None or priority == PRIORITY_NONE:
            continue
        
        # Пропускаем дубликаты базовых форм
        if base_form in seen_base_forms:
            continue
        
        seen_base_forms.add(base_form)
        ranked_words.append((base_form, priority))
    
    # Сортируем по приоритету (от высокого к низкому)
    ranked_words.sort(key=lambda x: x[1], reverse=True)
    
    return ranked_words


def clean_query(query: str) -> str:
    """
    Очищает запрос от незначащих слов, оставляя только юридические термины
    
    Args:
        query: Исходный запрос
        
    Returns:
        Очищенный запрос с только значимыми словами
    """
    ranked_words = rank_and_filter_query(query)
    
    # Берем только слова с приоритетом выше LOW (HIGH и MEDIUM)
    significant_words = [base_form for base_form, priority in ranked_words if priority > PRIORITY_LOW]
    
    if not significant_words:
        # Если нет высокоприоритетных слов, берем все значимые
        significant_words = [base_form for base_form, priority in ranked_words]
    
    return ' '.join(significant_words)


def get_priority_keywords(query: str, max_high: int = 5, max_medium: int = 10) -> List[str]:
    """
    Извлекает ключевые слова из запроса с приоритетом
    
    Args:
        query: Исходный запрос
        max_high: Максимальное количество высокоприоритетных слов
        max_medium: Максимальное количество среднеприоритетных слов
        
    Returns:
        Список ключевых слов, отсортированный по приоритету
    """
    ranked_words = rank_and_filter_query(query)
    
    keywords = []
    high_count = 0
    medium_count = 0
    
    for base_form, priority in ranked_words:
        if priority == PRIORITY_HIGH and high_count < max_high:
            keywords.append(base_form)
            high_count += 1
        elif priority == PRIORITY_MEDIUM and medium_count < max_medium:
            keywords.append(base_form)
            medium_count += 1
        elif priority == PRIORITY_LOW and len(keywords) < (max_high + max_medium):
            # Добавляем низкоприоритетные только если не набрали достаточно высокоприоритетных
            keywords.append(base_form)
    
    return keywords


